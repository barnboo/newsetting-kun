/**
 * Clean SVG content by stripping XML declarations and injecting colors
 */
export function cleanSvg(svg: string, color = '#000000'): string {
  let cleaned = svg.replace(/<\?xml[^>]*\?>/gi, '').trim();
  if (!cleaned.includes('xmlns=')) {
    cleaned = cleaned.replace('<svg ', '<svg xmlns="http://www.w3.org/2000/svg" ');
  }
  return cleaned.replace(/#000000/g, color).replace(/#000(?=[;"'\s>])/g, color);
}

