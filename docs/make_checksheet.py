def main():
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "debug_checksheet.csv")
    with open(out, "w", newline="", encoding="utf-8-sig") as f:
        w = csv.writer(f)
        w.writerow(HEADER)
        counters = {}
        for cat, sub, item, step, exp, pri in ROWS:
            key = cat.split(".")[0]
            counters[key] = counters.get(key, 0) + 1
            w.writerow([f"{key}-{counters[key]:02d}", cat, sub, item, step, exp, pri,
                        "未実施", "", "", "", ""])
    print(f"wrote {out} ({len(ROWS)} rows)")


if __name__ == "__main__":
    main()
